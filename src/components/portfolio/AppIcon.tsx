export function getLucideIcon(name?: string): ComponentType<LucideProps> | null {
  if (!name) return null
  const key = name.toLowerCase().trim().replace(/[-\s]+/g, '_')
  return ICON_MAP[key] ?? null
}

interface AppIconProps extends LucideProps {
  name?: string
  fallback?: ComponentType<LucideProps>
}

export function AppIcon({ name, fallback: Fallback = Globe, ...props }: AppIconProps) {
  if (!name) return null
  const Component = getLucideIcon(name) || Fallback
  return <Component {...props} />
}


